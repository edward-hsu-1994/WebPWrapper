namespace WebPWrapper.Decoder {
    /// <summary>Supported output formats for WebP decoding.</summary>
    public enum ExportFormats {
        /// <summary>Portable Network Graphics format.</summary>
        PNG,
        /// <summary>Tagged Image File Format.</summary>
        TIFF,
        /// <summary>Portable Arbitrary Map format.</summary>
        PAM,
        /// <summary>Portable Pixmap format.</summary>
        PPM,
        /// <summary>Portable Graymap format.</summary>
        PGM,
        /// <summary>Raw YUV format.</summary>
        YUV,
        /// <summary>Windows bitmap format.</summary>
        BMP
    }
}